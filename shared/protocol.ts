import type { Game, Seat } from "./game.js";
import type { Mention } from "./chat.js";
import type { RoomEffects, SoundCatalog } from "./effects.js";
export type Typing = {
  room: string;
  playerId: string;
  name: string;
  color: string;
  active: boolean;
};
export type Voice = {
  senderId?: string;
  id: string;
  name: string;
  color: string;
  mime: string;
  duration: number;
  at: number;
};
export type Chat = {
  senderId?: string;
  id: string;
  name: string;
  color: string;
  text: string;
  replyTo?: string;
  mentions?: Mention[];
  gif?: { id: string; width: number; height: number };
  photo?: { id: string; width: number; height: number; mime: "image/jpeg" };
  at: number;
};
export type Room = {
  effects?: RoomEffects;
  joinOrder?: string[];
  actionReadyAt?: number;
  botDifficulty?: number;
  finishMode?: "first" | "all";
  archived?: boolean;
  code: string;
  name: string;
  public: boolean;
  host: string;
  seats: (Seat | null)[];
  game: Game | null;
  voices: Voice[];
  chat: Chat[];
  createdAt: number;
  updatedAt: number;
  lastHumanAt: number;
  spectators?: string[];
  spectatorNames?: Record<string, string>;
};
export type PublicRoom = {
  code: string;
  name: string;
  players: number;
  bots: number;
  spectators?: number;
  gameStarted?: boolean;
};
export type Reply = {
  effects?: RoomEffects;
  soundCatalog?: SoundCatalog;
  code?: string;
  serverNow?: number;
  ok: boolean;
  error?: string;
  room?: Room;
  roomMissing?: boolean;
  me?: string;
  rooms?: PublicRoom[];
  roomPage?: { page: number; pageSize: number; total: number; pages: number };
};
